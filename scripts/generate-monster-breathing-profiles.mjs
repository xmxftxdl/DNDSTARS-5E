import fs from 'node:fs'
const source = new URL('../src/rulesets/dnd5e/generated/srdMonsters.generated.json', import.meta.url)
const catalog = JSON.parse(fs.readFileSync(source, 'utf8'))
const profiles = Object.fromEntries(catalog.monsters.map(monster => {
  const traits = monster.traits ?? []
  const canBreatheWater = traits.some(trait => ['Amphibious', 'Limited Amphibiousness', 'Water Breathing'].includes(trait.name))
  const hold = traits.find(trait => trait.name === 'Hold Breath')?.description.match(/can hold its breath for (\d+) (minute|hour)s?/)
  return [monster.id, { constitutionScore: monster.abilities.con,
    ...(canBreatheWater ? { canBreatheWater: true } : {}),
    ...(hold ? { holdBreathSeconds: Number(hold[1]) * (hold[2] === 'hour' ? 3600 : 60) } : {}) }]
}))
fs.writeFileSync(new URL('../shared/monster-breathing-profiles.mjs', import.meta.url),
  '// Generated by scripts/generate-monster-breathing-profiles.mjs from the bundled SRD 5.1 catalog.\n' +
  `// Source: ${catalog.source.rulesUrl}; ${catalog.source.license}.\n` +
  `export const monsterBreathingProfiles = ${JSON.stringify(profiles, null, 2)}\n`)
